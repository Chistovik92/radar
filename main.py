async def prepare_database() -> None:
    """Готовит базу: ждёт готовности, создаёт схему, переносит старые данные."""
    await db_engine.wait_ready()

    log.info("Проверяю схему базы")
    created, tables, repaired = await db_engine.ensure_schema()
    await db_engine.stamp_alembic()
    if repaired:
        log.warning("Схема была несовместима и пересоздана (%d таблиц)", tables)
    elif created:
        log.info("Схема базы создана (%d таблиц)", tables)
    else:
        log.info("Схема базы актуальна (%d таблиц)", tables)
    if await importer.is_empty() and importer.legacy_present():
        # Импортёр db.json удалён в 4.6.1. Молча стартовать с пустой базой
        # нельзя: человек решит, что данные потеряны, а они лежат рядом.
        log.error(
            "Рядом лежит data/db.json от версии 3.x, но перенос из него "
            "прекращён с 4.6.1. Обновитесь сначала до 4.6.0 — она перенесёт "
            "данные, — и только потом на эту версию. Подробности в README, "
            "раздел «Обновление с прежних версий»."
        )
    await storage.load()
    features.apply(await repo.load_features())
    active = sum(1 for flag in features.FLAGS if features.enabled(flag.key))
    log.info("Возможностей включено: %d из %d", active, len(features.FLAGS))
    logstore.ensure_directory()
    stale_logs = logstore.purge_old()
    if stale_logs:
        log.info("Удалено устаревших журналов: %d", stale_logs)

    removed = await repo.purge_old_events()
    if removed:
        log.info("Удалено устаревших событий: %d", removed)


async def main() -> None:
    await prepare_database()

    dp.message.outer_middleware(AccessMiddleware())
    dp.callback_query.outer_middleware(AccessMiddleware())
    handlers.setup(dp)

    log.info(
        "Запуск «Радар» v%s | ИИ: %s | TZ: %s | опрос каждые %d с",
        config.VERSION,
        config.GEMINI_MODEL if config.AI_ENABLED else "выключен (эвристика)",
        os.getenv("TZ", "system"),
        config.POLL_INTERVAL,
    )

    if ai.ENABLED:
        await ai.discover_models()
        log.info(
            "Модели: ассистент «%s», анализ «%s»",
            ai.current_model(ai.ASSISTANT), ai.current_model(ai.ANALYSIS),
        )

    await setup_commands()

    background = asyncio.create_task(monitor.run(), name="monitor")

    # Веб-панель — отдельная задача: её сбой не должен касаться оповещений
    panel_task = None
    if features.enabled("web_panel"):
        from radar.web import run as run_panel

        panel_task = asyncio.create_task(run_panel(), name="web-panel")
    asyncio.create_task(announce(), name="announce")

    # Адаптер MAX. Пакет radar/platforms/ существовал с 4.4 и не
    # импортировался ни одним модулем — флаг «Мессенджер MAX» значился
    # в списке возможностей и не мог ничего включить.
    #
    # Запускается отдельной задачей и только по флагу: реализация
    # не проверялась на живом сервере, и она не должна мешать Telegram,
    # если MAX ответит не тем, чего мы ждём.
    if features.enabled("platform_max"):
        from radar.platforms.max import MaxTransport

        max_transport = MaxTransport()
        if max_transport.configured:
            asyncio.create_task(max_transport.start(), name="max")
            log.info("Адаптер MAX запущен")
        else:
            log.warning(
                "Мессенджер MAX включён флагом, но MAX_BOT_TOKEN пуст — "
                "адаптер не запускается"
            )

    try:
        await bot.delete_webhook(drop_pending_updates=True)
        await dp.start_polling(bot, allowed_updates=dp.resolve_used_update_types())
    finally:
        background.cancel()
        try:
            await background
        except asyncio.CancelledError:
            pass
        if panel_task is not None:
            panel_task.cancel()
        await bot.session.close()
        await db_engine.dispose()
        log.info("Остановлено")


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except (KeyboardInterrupt, SystemExit):
        pass
    except db_engine.AuthenticationError:
        # Причина уже подробно объяснена в логе — трассировка тут лишний шум.
        raise SystemExit(1)
    except Exception:  # noqa: BLE001
        # Без этого контейнер уходит в бесконечный цикл рестартов, а причина
        # теряется среди одинаковых трейсбеков.
        log.critical("Критический сбой при запуске", exc_info=True)
        log.critical(
            "Проверьте .env (DB_PASSWORD без символа $), доступность базы "
            "и логи radar_db: docker logs --tail 40 radar_db"
        )
        raise SystemExit(1)
